def connect_master():
    connection = sqlite3.connect(MASTER_DB)
    connection.row_factory = sqlite3.Row
    return connection


def family_db_path(family_id):
    # The filename is generated by the server. Clients never choose it.
    if not re.fullmatch(r"[A-F0-9]{12}", family_id):
        raise ValueError("Invalid family id.")
    return os.path.join(FAMILY_DB_DIR, f"family_{family_id}.db")


def connect_family(family_id):
    connection = sqlite3.connect(family_db_path(family_id))
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def create_family_database(family_id):
    connection = connect_family(family_id)
    try:
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS members (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER UNIQUE NOT NULL,
                name TEXT NOT NULL,
                email TEXT NOT NULL,
                relationship TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS memories (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                member_id INTEGER NOT NULL,
                memory_text TEXT,
                transcript TEXT,
                audio_filename TEXT,
                summary TEXT,
                tags TEXT,
                created_by INTEGER NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(member_id) REFERENCES members(id)
            );
            """
        )
        connection.commit()
    finally:
        connection.close()


def init_master_database():
    connection = connect_master()
    try:
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS families (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                join_code TEXT UNIQUE NOT NULL,
                database_file TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                family_id TEXT NOT NULL,
                name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'member',
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(family_id) REFERENCES families(id)
            );
            """
        )
        connection.commit()
    finally:
        connection.close()


def clean_text(value, max_length=10000):
    if value is None:
        return ""
    return str(value).strip()[:max_length]


def allowed_audio(filename):
    return "." in filename and filename.rsplit(".", 1)[1].lower() in ALLOWED_AUDIO_EXTENSIONS


def make_title(text, fallback="Family Memory"):
    words = re.findall(r"\S+", clean_text(text, 240))
    if not words:
        return fallback
    title = " ".join(words[:8]).strip(" .,!?:;")
    return title + ("..." if len(words) > 8 else "")


def make_summary(text):
    text = clean_text(text)
    if not text:
        return ""
    sentences = re.split(r"(?<=[.!?])\s+", text)
    useful = " ".join(sentences[:2]).strip()
    words = useful.split()
    return " ".join(words[:45]) + ("..." if len(words) > 45 else "")


def make_tags(text):
    lower = clean_text(text).lower()
    found = []
    for tag, keywords in TAG_KEYWORDS.items():
        if any(keyword in lower for keyword in keywords):
            found.append(tag)
    return found[:6]


def generate_join_code():
    alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    return "".join(secrets.choice(alphabet) for _ in range(8))


def create_token(user):
    return create_access_token(
        identity=str(user["id"]),
        additional_claims={"family_id": user["family_id"], "role": user["role"]},
    )


def user_payload(user, family):
    return {
        "id": user["id"],
        "name": user["name"],
        "email": user["email"],
        "role": user["role"],
        "family": {
            "id": family["id"],
            "name": family["name"],
            "join_code": family["join_code"],
        },
    }


def get_current_context():
    user_id = get_jwt_identity()
    connection = connect_master()
    try:
        user = connection.execute(
            "SELECT * FROM users WHERE id = ?", (int(user_id),)
        ).fetchone()
        if not user:
            return None, None
        family = connection.execute(
            "SELECT * FROM families WHERE id = ?", (user["family_id"],)
        ).fetchone()
        return user, family
    finally:
        connection.close()


def memory_to_dict(memory):
    return {
        "id": memory["id"],
        "title": memory["title"],
        "member_id": memory["member_id"],
        "family_member": memory["member_name"],
        "relationship": memory["relationship"],
        "memory_text": memory["memory_text"] or "",
        "transcript": memory["transcript"] or "",
        "summary": memory["summary"] or "",
        "tags": [tag for tag in (memory["tags"] or "").split(",") if tag],
        "audio_url": (
            f"/api/memories/{memory['id']}/audio"
            if memory["audio_filename"]
            else None
        ),
        "created_at": memory["created_at"],
    }


def find_memory(connection, memory_id):
    return connection.execute(
        """
        SELECT memories.*, members.name AS member_name, members.relationship
        FROM memories
        JOIN members ON members.id = memories.member_id
        WHERE memories.id = ?
        """,
        (memory_id,),
    ).fetchone()


