@app.get("/api/memories")
@jwt_required()
def list_memories():
    user, family = get_current_context()
    if not user or not family:
        return jsonify({"message": "Family not found."}), 404

    query = clean_text(request.args.get("q"), 120)
    connection = connect_family(family["id"])
    try:
        sql = """
            SELECT memories.*, members.name AS member_name, members.relationship
            FROM memories
            JOIN members ON members.id = memories.member_id
        """
        params = []
        if query:
            pattern = f"%{query}%"
            sql += """
                WHERE memories.title LIKE ?
                   OR members.name LIKE ?
                   OR members.relationship LIKE ?
                   OR memories.memory_text LIKE ?
                   OR memories.transcript LIKE ?
                   OR memories.tags LIKE ?
            """
            params = [pattern] * 6
        sql += " ORDER BY memories.created_at DESC"
        memories = connection.execute(sql, params).fetchall()
        return jsonify([memory_to_dict(memory) for memory in memories])
    finally:
        connection.close()


@app.post("/api/memories")
@jwt_required()
def create_memory():
    user, family = get_current_context()
    if not user or not family:
        return jsonify({"message": "Family not found."}), 404

    try:
        member_id = int(request.form.get("member_id", "0"))
    except ValueError:
        member_id = 0

    title = clean_text(request.form.get("title"), 180)
    memory_text = clean_text(request.form.get("memory_text"))
    transcript = clean_text(request.form.get("transcript"))

    connection = connect_family(family["id"])
    try:
        member = connection.execute(
            "SELECT * FROM members WHERE id = ?", (member_id,)
        ).fetchone()
        if not member:
            return jsonify({"message": "Please select a valid family member."}), 400

        audio_filename = None
        audio = request.files.get("audio")
        if audio and audio.filename:
            original = secure_filename(audio.filename)
            if not allowed_audio(original):
                return jsonify({"message": "Unsupported audio format."}), 400
            extension = original.rsplit(".", 1)[1].lower()
            audio_filename = f"{uuid.uuid4().hex}.{extension}"
            audio.save(os.path.join(UPLOAD_DIR, audio_filename))

        combined_text = transcript or memory_text
        if not combined_text and not audio_filename:
            return jsonify({"message": "Please add text, a transcript, or an audio recording."}), 400

        cursor = connection.execute(
            """
            INSERT INTO memories
                (title, member_id, memory_text, transcript, audio_filename, summary, tags, created_by)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                title or make_title(combined_text, f"Memory of {member['name']}"),
                member_id,
                memory_text,
                transcript,
                audio_filename,
                make_summary(combined_text),
                ",".join(make_tags(combined_text)),
                user["id"],
            ),
        )
        memory_id = cursor.lastrowid
        connection.commit()
        memory = find_memory(connection, memory_id)
        return jsonify(memory_to_dict(memory)), 201
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


